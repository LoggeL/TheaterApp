import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { initializeApp, deleteApp } from 'firebase-admin/app';
import { getAuth } from 'firebase-admin/auth';
import { Store } from '../src/store.mjs';
import { Theater } from '../src/theater.mjs';
import { Passkeys } from '../src/passkeys.mjs';
import { createHttpServer } from '../src/http.mjs';
import { authenticator } from './helpers/passkey-authenticator.mjs';

// Explicit opt-in, local emulator only. Never creates users in a real project.
const host = process.env.FIREBASE_AUTH_EMULATOR_HOST;
test('Firebase emulator exchanges a verified passkey, refreshes its claims and preserves password recovery', { skip: !host }, async t => {
  assert.match(host, /^(127\.0\.0\.1|localhost):\d+$/);
  const app = initializeApp({ projectId: 'demo-theater-passkeys' }, randomUUID());
  const auth = getAuth(app), uid = `passkey-${randomUUID()}`;
  const email = `${uid}@example.invalid`, password = 'SyntheticEmulatorPassword!234';
  await auth.createUser({ uid, email, emailVerified: true, password, displayName: 'Passkey Test' });
  t.after(async () => { await auth.deleteUser(uid); await deleteApp(app); });
  const firebase = async (method, data) => {
    const r = await fetch(`http://${host}/identitytoolkit.googleapis.com/v1/accounts:${method}?key=fake-emulator-key`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(data) });
    assert.equal(r.status, 200, `Firebase ${method}`); return r.json();
  };
  const normal = await firebase('signInWithPassword', { email, password, returnSecureToken: true });
  const store = new Store(); t.after(() => store.close());
  const theater = new Theater(store, { bootstrapEmail: email });
  theater.session(await auth.verifyIdToken(normal.idToken, true));
  const passkeys = new Passkeys({ theater, auth, rpId: 'app.example.com', webOrigins: ['https://app.example.com'] });
  const server = createHttpServer({ theater, passkeys, verifyToken: token => auth.verifyIdToken(token, true) });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => new Promise(resolve => server.close(resolve)));
  const request = (path, method, token, body) => fetch(`http://127.0.0.1:${server.address().port}/api/mobile/v1${path}`, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const device = authenticator();
  const options = await request('/passkeys/options', 'POST', normal.idToken, { name: 'Emulator key' });
  assert.equal(options.status, 200);
  const start = await options.json();
  const registered = await request('/passkeys/verify', 'POST', normal.idToken, { challengeId: start.challengeId, response: device.register(start.options) });
  assert.equal(registered.status, 200);
  const key = (await registered.json()).passkeys[0];
  const login = await (await request('/auth/passkeys/options', 'POST', null, {})).json();
  const verified = await request('/auth/passkeys/verify', 'POST', null, { challengeId: login.challengeId, response: device.authenticate(login.options) });
  assert.equal(verified.status, 200);
  const signed = await verified.json();
  assert.equal(signed.uid, uid);
  const session = await firebase('signInWithCustomToken', { token: signed.token, returnSecureToken: true });
  const claims = await auth.verifyIdToken(session.idToken, true);
  assert.equal(claims.uid, uid);
  assert.equal(claims.email_verified, true);
  assert.equal(claims.firebase.sign_in_provider, 'custom');
  assert.equal(claims.theater_passkey, key.id);
  assert.equal((await request('/auth/session', 'GET', session.idToken)).status, 200);
  const refreshed = await fetch(`http://${host}/securetoken.googleapis.com/v1/token?key=fake-emulator-key`, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ grant_type: 'refresh_token', refresh_token: session.refreshToken }) });
  assert.equal(refreshed.status, 200);
  const refresh = await refreshed.json();
  assert.equal((await auth.verifyIdToken(refresh.id_token)).theater_passkey, key.id);
  assert.equal((await request(`/passkeys/${key.id}`, 'DELETE', normal.idToken)).status, 200);
  assert.equal((await request('/auth/session', 'GET', refresh.id_token)).status, 401);
  const recovery = await firebase('signInWithPassword', { email, password, returnSecureToken: true });
  assert.equal(recovery.localId, uid);
  assert.equal((await request('/auth/session', 'GET', recovery.idToken)).status, 200);
});
